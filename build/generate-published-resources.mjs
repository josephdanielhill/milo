#!/usr/bin/env node
// Reads the resource files committed at the repository root and writes a
// static manifest that the app bundles as its default, read-only "published"
// library — so content merged to main shows up for everyone, not just
// whoever has that folder connected locally.
import { mkdir, readdir, readFile, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const projectRoot = dirname(dirname(fileURLToPath(import.meta.url)));

const collectionFileNames = [
  "books.json",
  "videos.json",
  "conferences.json",
  "training.json",
  "articles.json",
  "podcasts.json",
];

const markdownFolders = ["prompts", "skills", "tools"];

const forumCollectionPath = "forum/collections.json";

async function readIfExists(path) {
  try {
    return await readFile(path, "utf8");
  } catch (error) {
    if (error.code === "ENOENT") return null;
    throw error;
  }
}

async function collectMarkdownFiles(folder) {
  const dirPath = join(projectRoot, folder);
  let entries;
  try {
    entries = await readdir(dirPath, { withFileTypes: true });
  } catch (error) {
    if (error.code === "ENOENT") return [];
    throw error;
  }
  const files = [];
  for (const entry of entries) {
    if (!entry.isFile() || !entry.name.toLowerCase().endsWith(".md")) continue;
    const raw = await readFile(join(dirPath, entry.name), "utf8");
    files.push({ path: `${folder}/${entry.name}`, raw });
  }
  return files;
}

async function main() {
  const collections = {};
  for (const filename of collectionFileNames) {
    const raw = await readIfExists(join(projectRoot, filename));
    if (raw !== null) collections[filename] = raw;
  }

  const files = [];
  for (const folder of markdownFolders) {
    files.push(...(await collectMarkdownFiles(folder)));
  }

  const forumRaw = await readIfExists(join(projectRoot, forumCollectionPath));

  const outDir = join(projectRoot, "app", "generated");
  await mkdir(outDir, { recursive: true });

  const contents = `// Auto-generated by build/generate-published-resources.mjs — do not edit by hand.
// Regenerated on every dev/build run from the resource files committed to the repository root.

export const publishedCollectionFiles: Record<string, string> = ${JSON.stringify(collections, null, 2)};

export const publishedResourceFiles: { path: string; raw: string }[] = ${JSON.stringify(files, null, 2)};

${forumRaw !== null ? `export const publishedForumCollections = ${forumRaw};` : 'export const publishedForumCollections = { version: 1, collections: [] };'}
`;

  await writeFile(join(outDir, "published-manifest.ts"), contents);
}

main().catch((error) => {
  console.error(error);
  process.exitCode = 1;
});
